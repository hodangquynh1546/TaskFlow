using System.Collections.Concurrent;
using Microsoft.Extensions.Logging;

namespace TaskManagement.IntegrationTests.Infrastructure;

public sealed record LogEntry(LogLevel Level, string Category, string Message, Exception? Exception);

public sealed class CapturingLoggerProvider : ILoggerProvider
{
    public ConcurrentQueue<LogEntry> Entries { get; } = new();

    public ILogger CreateLogger(string categoryName) => new CapturingLogger(categoryName, Entries);

    public void Dispose()
    {
    }

    private sealed class CapturingLogger(string category, ConcurrentQueue<LogEntry> sink) : ILogger
    {
        public IDisposable? BeginScope<TState>(TState state) where TState : notnull => null;

        public bool IsEnabled(LogLevel logLevel) => true;

        public void Log<TState>(LogLevel logLevel, EventId eventId, TState state, Exception? exception, Func<TState, Exception?, string> formatter) =>
            sink.Enqueue(new LogEntry(logLevel, category, formatter(state, exception), exception));
    }
}
